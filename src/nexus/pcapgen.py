"""Build synthetic Ethernet frames and pcap files (tests and the demo).

Everything here is deterministic for a given seed, so the sample capture in
the README can be regenerated byte-for-byte.
"""

from __future__ import annotations

import random
import struct
from collections.abc import Iterable
from pathlib import Path

from nexus.pcap import inet_checksum

MAC_A = bytes.fromhex("020000000001")
MAC_B = bytes.fromhex("020000000002")


def eth(ethertype: int, payload: bytes, vlans: Iterable[int] = ()) -> bytes:
    tags = list(vlans)
    hdr = MAC_B + MAC_A
    for i, vid in enumerate(tags):
        tpid = 0x88A8 if (i == 0 and len(tags) > 1) else 0x8100
        hdr += struct.pack("!HH", tpid, vid & 0x0FFF)
    return hdr + struct.pack("!H", ethertype) + payload


def ipv4(
    src: str,
    dst: str,
    proto: int,
    payload: bytes,
    *,
    frag: int = 0,
    ttl: int = 64,
    bad_csum: bool = False,
) -> bytes:
    s = bytes(int(x) for x in src.split("."))
    d = bytes(int(x) for x in dst.split("."))
    hdr = struct.pack(
        "!BBHHHBBH4s4s", 0x45, 0, 20 + len(payload), 0x1C46, frag, ttl, proto, 0, s, d
    )
    csum = inet_checksum(hdr)
    if bad_csum:
        csum ^= 0x5A5A
    return hdr[:10] + struct.pack("!H", csum) + hdr[12:] + payload


def ipv6(src_last: int, dst_last: int, nh: int, payload: bytes) -> bytes:
    pre = bytes.fromhex("20010db8000000000000000000000000")
    s = pre[:15] + bytes([src_last])
    d = pre[:15] + bytes([dst_last])
    return struct.pack("!IHBB", 0x60000000, len(payload), nh, 64) + s + d + payload


def udp(sp: int, dp: int, data: bytes = b"") -> bytes:
    return struct.pack("!HHHH", sp, dp, 8 + len(data), 0) + data


def tcp(sp: int, dp: int, data: bytes = b"", flags: int = 0x18) -> bytes:
    return struct.pack("!HHIIBBHHH", sp, dp, 1, 1, 0x50, flags, 65535, 0, 0) + data


def icmp_echo(data: bytes = b"ping") -> bytes:
    return struct.pack("!BBHHH", 8, 0, 0, 1, 1) + data


def arp() -> bytes:
    return bytes(28)


def write_pcap(
    path: str | Path,
    frames: Iterable[tuple[float, bytes, int | None]],
    *,
    snaplen: int = 65535,
    big_endian: bool = False,
    nsec: bool = False,
) -> None:
    """``frames`` yields (timestamp, frame_bytes, wire_len or None)."""
    o = ">" if big_endian else "<"
    magic = 0xA1B23C4D if nsec else 0xA1B2C3D4
    out = bytearray(struct.pack(o + "IHHiIII", magic, 2, 4, 0, 0, snaplen, 1))
    for ts, frame, wire in frames:
        sec = int(ts)
        frac = round((ts - sec) * (1e9 if nsec else 1e6))
        cap = frame[:snaplen]
        out += struct.pack(o + "IIII", sec, frac, len(cap), wire if wire else len(frame)) + cap
    Path(path).write_bytes(bytes(out))


def sample_frames(seed: int = 7, n_background: int = 200) -> list[tuple[float, bytes, int | None]]:
    """A small mixed capture: a few heavy TCP flows, DNS, VLAN/QinQ traffic,
    IPv6, ARP, ICMP, a fragment pair, a bad IPv4 checksum and a snaplen cut."""
    rng = random.Random(seed)
    t = 1_793_000_000.0
    frames: list[tuple[float, bytes, int | None]] = []

    def add(frame: bytes, wire: int | None = None) -> None:
        nonlocal t
        t += rng.uniform(0.0005, 0.004)
        frames.append((t, frame, wire))

    for _ in range(n_background):
        r = rng.random()
        if r < 0.45:  # bulk transfer 10.0.10.5 -> 10.0.20.8:443
            add(eth(0x0800, ipv4("10.0.10.5", "10.0.20.8", 6, tcp(51514, 443, bytes(1200)))))
        elif r < 0.60:  # replication on VLAN 20
            add(
                eth(
                    0x0800,
                    ipv4("10.0.20.11", "10.0.20.12", 6, tcp(7000, 7001, bytes(800))),
                    vlans=[20],
                )
            )
        elif r < 0.75:  # DNS
            sp = rng.choice([53001, 53002, 53003])
            add(eth(0x0800, ipv4("10.0.10.5", "10.0.0.53", 17, udp(sp, 53, bytes(40)))))
        elif r < 0.85:  # IPv6 TCP
            add(eth(0x86DD, ipv6(1, 2, 6, tcp(40000, 8443, bytes(300)))))
        elif r < 0.90:  # provider QinQ
            add(
                eth(
                    0x0800,
                    ipv4("192.0.2.1", "192.0.2.2", 17, udp(4789, 4789, bytes(100))),
                    vlans=[300, 99],
                )
            )
        elif r < 0.95:
            add(eth(0x0806, arp()))
        else:
            add(eth(0x0800, ipv4("10.0.0.2", "10.0.0.1", 1, icmp_echo())))
    # one fragmented UDP datagram (first + non-first fragment)
    add(eth(0x0800, ipv4("10.0.10.9", "10.0.20.9", 17, udp(5000, 5001, bytes(64)), frag=0x2000)))
    add(eth(0x0800, ipv4("10.0.10.9", "10.0.20.9", 17, bytes(64), frag=0x0009)))
    # corrupted IPv4 header checksum
    add(eth(0x0800, ipv4("10.0.10.66", "10.0.20.66", 17, udp(1234, 4321, b"x"), bad_csum=True)))
    # a frame cut by a 34-byte capture snaplen (L4 header missing)
    full = eth(0x0800, ipv4("10.0.10.7", "10.0.20.7", 6, tcp(1111, 2222, bytes(500))))
    add(full[:34], len(full))
    return frames


def write_sample(path: str | Path, seed: int = 7) -> None:
    write_pcap(path, sample_frames(seed))


if __name__ == "__main__":  # pragma: no cover
    import sys

    write_sample(sys.argv[1] if len(sys.argv) > 1 else "sample.pcap")
